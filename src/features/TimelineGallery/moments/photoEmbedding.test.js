import { resolvePhotoEmbedding } from './embeddingResolver';
import { generateSyntheticEmbedding } from '../../../services/geminiEmbeddingService';
import { runPhotoEmbeddingBatch } from '../../../services/photoEmbeddingOrchestrator';
import { detectSegmentMoments } from './momentDetectionEngine';

describe('Photo Embedding Integration with Moment Detection', () => {
  it('resolves embeddings generated by the embedding pipeline', () => {
    const vector = generateSyntheticEmbedding('photo-test-123', 64);
    const photo = {
      id: 'photo-test-123',
      name: 'IMG_0001.JPG',
      embeddings: {
        geminiEmbedding2: {
          vector,
          model: 'gemini-embedding-2',
          dimension: 64,
          updatedAt: '2026-11-01T10:00:00.000Z',
        },
      },
    };

    const resolved = resolvePhotoEmbedding(photo);
    expect(resolved.vector).toEqual(vector);
    expect(resolved.dimension).toBe(64);
    expect(resolved.source).toBe('embeddings.geminiEmbedding2');
  });

  it('enables Moment Detection to cluster photos once embeddings are added', async () => {
    // 4 photos within short temporal intervals (1 minute apart)
    const basePhotos = [
      { id: 'p1', name: 'img1.jpg', dateTimeOriginal: '2026-11-01T10:00:00Z', url: 'https://cdn.fotoflow.co/1.jpg' },
      { id: 'p2', name: 'img2.jpg', dateTimeOriginal: '2026-11-01T10:01:00Z', url: 'https://cdn.fotoflow.co/2.jpg' },
      { id: 'p3', name: 'img3.jpg', dateTimeOriginal: '2026-11-01T10:02:00Z', url: 'https://cdn.fotoflow.co/3.jpg' },
      { id: 'p4', name: 'img4.jpg', dateTimeOriginal: '2026-11-01T10:03:00Z', url: 'https://cdn.fotoflow.co/4.jpg' },
    ];

    // Initially, none have embeddings
    const initialSegment = {
      id: 'seg-1',
      photoIds: basePhotos.map((p) => p.id),
      photos: basePhotos,
      startTime: Date.parse(basePhotos[0].dateTimeOriginal),
      endTime: Date.parse(basePhotos[3].dateTimeOriginal),
    };

    const initialDetection = detectSegmentMoments(initialSegment, { enabled: true });
    // All 4 photos are unassigned due to missing embeddings
    expect(initialDetection.unassignedPhotos).toHaveLength(4);
    expect(initialDetection.moments).toHaveLength(0);

    // Generate embeddings for first 3 photos (user decides to embed 3 photos)
    const embeddingResult = await runPhotoEmbeddingBatch({
      photos: basePhotos,
      photoCount: 3,
      onlyMissing: true,
      useSynthetic: true,
      dimension: 32,
    });

    expect(embeddingResult.successful).toHaveLength(3);

    // Apply updated embeddings to photos
    const updatedPhotos = basePhotos.map((photo) => {
      const updates = embeddingResult.updatedMap[photo.id];
      if (!updates) return photo;
      return { ...photo, ...updates };
    });

    const updatedSegment = {
      id: 'seg-1',
      photoIds: updatedPhotos.map((p) => p.id),
      photos: updatedPhotos,
      startTime: Date.parse(updatedPhotos[0].dateTimeOriginal),
      endTime: Date.parse(updatedPhotos[3].dateTimeOriginal),
    };

    const updatedDetection = detectSegmentMoments(updatedSegment, { enabled: true, minMomentSize: 2 });
    // p4 still has missing embedding, but p1, p2, p3 have embeddings and form moments or candidate clusters!
    const unassignedReasons = updatedDetection.unassignedPhotos.map((u) => u.reason);
    expect(unassignedReasons).toContain('missing-embedding');
    // The photos with embeddings were collected and evaluated
    expect(updatedDetection.photosWithEmbeddings).toBe(3);
    expect(updatedDetection.photosWithoutEmbeddings).toBe(1);
  });
});
